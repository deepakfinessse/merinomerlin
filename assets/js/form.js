/* ── S08 poc — 08-poc.html ── */
/* Request form endpoint (POC / demo) — the merinoservices.com Laravel API. Leave '' and nothing is sent anywhere:
   the form confirms in place. Keep the bare host: www.merinoservices.com 301-redirects, which breaks the CORS preflight.
   POSTs JSON:
     { request_type: "poc" | "demo", name, email, company, department, questions, website }
   `website` is the hidden spam-trap field: the server silently drops the request when it is filled in.
   2xx sends the visitor to thank-you.html?type=<request_type>. 422 shows the server's message under each field
   ({ errors: { field: [msg] } }), 429 asks the visitor to wait a minute. Anything else (other non-2xx, network
   error, 10 s timeout) keeps the form on screen with an error message and re-enables the button. */
const FORM_ENDPOINT = 'https://merinoservices.com/api/merlin/request';
(() => {
  'use strict';
  const root = document.getElementById('poc');
  if (!root) return;
  const { $, $$ } = MM;

  /* ── request form: intent, validation, in-page confirmation ────────────────────────────── */
  const card = $('#request', root);
  const body = $('.poc__body', card);
  const form = $('#poc-form', card);
  const done = $('.poc__done', card);
  const submit = $('.poc__submit', card);
  const formErr = $('#poc-form-err', form);
  const radios = $$('input[name="poc-intent"]', form);
  const EMAIL = /^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/;
  let intent = 'poc';

  const fields = {
    name: { el: $('#poc-name', form), msg: 'Please enter your name.', ok: v => v.trim() !== '' },
    email: { el: $('#poc-email', form), msg: 'Please enter a valid work email.', ok: v => EMAIL.test(v.trim()) },
    company: { el: $('#poc-company', form), msg: 'Please enter your company.', ok: v => v.trim() !== '' },
    department: { el: $('#poc-dept', form), msg: 'Please choose a department to start with.', ok: v => v !== '' },
    // the API requires 10–2000 characters for both intents
    questions: { el: $('#poc-questions', form), msg: 'Please add at least one real question (10–2000 characters).', ok: v => { const n = v.trim().length; return n >= 10 && n <= 2000; } }
  };
  const trap = $('input[name="website"]', form);   // spam trap: hidden from people, sent as-is
  const order = Object.keys(fields);
  form.noValidate = true;               // the script validates; without JS the native constraints still apply

  const setError = (key, message) => {
    const f = fields[key], err = $('#' + f.el.id + '-err', form), txt = $('span', err);
    if (message) {
      txt.textContent = message; err.hidden = false;
      f.el.setAttribute('aria-invalid', 'true'); f.el.setAttribute('aria-describedby', err.id);
    } else {
      txt.textContent = ''; err.hidden = true;
      f.el.removeAttribute('aria-invalid'); f.el.removeAttribute('aria-describedby');
    }
  };
  const check = key => { const f = fields[key]; const good = f.ok(f.el.value); setError(key, good ? '' : f.msg); return good; };
  const clearAll = () => order.forEach(k => setError(k, ''));
  const marked = el => el.getAttribute('aria-invalid') === 'true';

  // form-level message: only used once FORM_ENDPOINT is set and a POST fails (never for local validation)
  const showFormError = message => {
    $('span', formErr).textContent = message;
    formErr.hidden = false;
    formErr.focus({ preventScroll: false });
  };
  const hideFormError = () => { formErr.hidden = true; $('span', formErr).textContent = ''; };

  order.forEach(key => {
    const f = fields[key], el = f.el;
    // once marked invalid: re-check when the field loses focus, per spec, and clear the message the moment the
    // value becomes valid — otherwise it would vanish as focus leaves for the submit button, shifting the button
    // away between mousedown and mouseup and swallowing the click.
    el.addEventListener('blur', () => { if (marked(el)) check(key); });
    el.addEventListener(el.tagName === 'SELECT' ? 'change' : 'input', () => {
      if (marked(el) && f.ok(el.value)) setError(key, '');
      hideFormError();   // a stale submit-error no longer applies once the user edits any field
    });
  });

  const setIntent = v => {
    if (v !== 'poc' && v !== 'demo') return;
    intent = v;
    card.setAttribute('data-mode', v);
    radios.forEach(r => { r.checked = r.value === v; });
  };
  form.addEventListener('change', e => { if (e.target && e.target.name === 'poc-intent') setIntent(e.target.value); });

  // back to an empty form (after a sent request); the current intent survives form.reset()
  const resetForm = () => {
    form.reset();
    clearAll();
    hideFormError();
    setIntent(intent);
    done.hidden = true;
    body.hidden = false;
    fit();
  };
  // A CTA clicked while the confirmation shows opens a fresh form in the new intent — it never rewrites the
  // confirmation of the request that was actually sent (that copy is frozen on done[data-mode] at submit).
  MM.on('intent', d => {
    if (!d || !d.intent) return;
    if (!done.hidden) {
      const had = done.contains(document.activeElement);
      resetForm();
      if (had) card.focus({ preventScroll: true });   // focus must not fall back to <body> with the hidden panel
    }
    setIntent(d.intent);
  });

  const demoLink = $('button.poc__priv-link', form);
  if (demoLink) demoLink.addEventListener('click', () => { setIntent('demo'); fields.name.el.focus(); });

  let sending = false;
  form.addEventListener('submit', async e => {
    e.preventDefault();
    if (sending) return;
    const bad = order.filter(k => !check(k));
    if (bad.length) { fields[bad[0]].el.focus(); return; }
    const data = {
      request_type: intent,
      name: fields.name.el.value.trim(),
      email: fields.email.el.value.trim(),
      company: fields.company.el.value.trim(),
      department: fields.department.el.value,
      questions: fields.questions.el.value.trim(),
      website: trap ? trap.value : ''
    };
    if (FORM_ENDPOINT) {
      sending = true; submit.setAttribute('aria-disabled', 'true'); hideFormError();
      const hasAbort = 'AbortController' in window;
      const controller = hasAbort ? new AbortController() : null;
      const timer = hasAbort ? setTimeout(() => controller.abort(), 10000) : null;
      let res = null, body = null;
      try {
        const opts = {
          method: 'POST',
          headers: { 'Content-Type': 'application/json', 'Accept': 'application/json' },
          body: JSON.stringify(data)
        };
        if (hasAbort) opts.signal = controller.signal;
        res = await fetch(FORM_ENDPOINT, opts);
        body = await res.json().catch(() => null);
      } catch (_) {
        res = null;
      } finally {
        if (timer) clearTimeout(timer);
      }
      if (res && res.ok) {
        window.location.assign('thank-you.html?type=' + data.request_type);
        return;                              // sending / aria-disabled stay set: a second click does nothing while it navigates
      }
      sending = false; submit.removeAttribute('aria-disabled');
      if (res && res.status === 422 && body && body.errors) {
        // server-side validation: show each message under its field; anything without a field goes to the form error
        const other = [];
        Object.keys(body.errors).forEach(k => {
          const msg = [].concat(body.errors[k])[0] || '';
          if (fields[k]) setError(k, msg); else other.push(msg);
        });
        if (other.length) showFormError(other[0]);
        const first = order.find(k => marked(fields[k].el));
        if (first && !other.length) fields[first].el.focus();
        return;
      }
      if (res && res.status === 429) { showFormError('Too many attempts. Please try again in a minute.'); return; }
      showFormError(res ? 'Something went wrong. Please try again or email us.' : 'Network error. Please check your connection and try again.');
      return;                                 // the in-page confirmation panel is never shown on failure
    }
    $('.poc__dn', done).textContent = data.name;
    $('.poc__de', done).textContent = data.email;
    done.setAttribute('data-mode', data.request_type);   // freeze the sentence for the request that was sent
    body.hidden = true;
    done.hidden = false;
    fit();                                  // the short confirmation fits: back to top-anchored sticky before measuring
    if (!MM.reduced) {
      done.classList.add('is-enter');
      await MM.raf2();
      done.classList.add('is-shown');
      done.classList.remove('is-enter');
      MM.sleep(360).then(() => done.classList.remove('is-shown'));
    }
    done.focus({ preventScroll: true });
    const r = card.getBoundingClientRect();
    if (r.top < MM.navH() || r.top > window.innerHeight * .6) MM.scrollTo(card, { focus: false });
  });

  $('.poc__again', done).addEventListener('click', () => { resetForm(); fields.name.el.focus(); });

  /* ── sticky form (≥ 1100) ──────────────────────────────────────────────────────────────
     Spec: sticky at nav + 24 px when the whole card fits the viewport (card height < innerHeight − navH − 48).
     At the spec's own field metrics the card is ~990 px, so on common desktop heights it does not fit: it then
     rides on its BOTTOM edge instead (CSS, .is-tall) — it scrolls normally until the submit button reaches the
     viewport bottom, then travels beside the steps and the golden set and ends flush with the golden set.
     While the card is the URL :target the tall variant is released, so every jump to #request lands on the
     card's own top (see the CSS). The script only measures and toggles classes. */
  const grid = card.parentElement;
  const desk = window.matchMedia('(min-width:1100px)');
  const fit = () => {
    if (!desk.matches) { card.classList.remove('is-sticky', 'is-tall'); return; }
    card.classList.toggle('is-tall', !(card.offsetHeight < window.innerHeight - MM.navH() - 48));
    card.classList.add('is-sticky');
  };
  fit();
  MM.on('resize', fit);
  MM.fontsReady.then(fit);
  if ('ResizeObserver' in window) new ResizeObserver(fit).observe(card);

  // Focus under the nav (Shift+Tab, the first invalid field after a submit): a bottom-anchored card moves with
  // the viewport, so the browser's own scroll-into-view cannot reveal its top. Scroll to the position where the
  // field clears the nav — at that y the card is either back in its own place or stuck with the field in view.
  // Two frames, so the measurement follows the error messages' layout and the class toggles they cause.
  card.addEventListener('focusin', e => {
    const el = e.target;
    MM.raf2().then(() => {
      if (document.activeElement !== el || !card.classList.contains('is-tall') || !card.classList.contains('is-sticky') ||
        card.matches(':target')) return;
      const nav = MM.navH(), r = el.getBoundingClientRect();
      if (r.top >= nav + 8) return;
      const box = (el.closest('.field, .seg') || el).getBoundingClientRect();     // bring its label along
      const offset = box.top - card.getBoundingClientRect().top;
      const place = grid.getBoundingClientRect().top + window.scrollY + (parseFloat(getComputedStyle(card).marginTop) || 0);
      MM.scrollTo(place + offset - nav - 16);
    });
  });
})();

/* ── S10 footer — 10-footer.html ── */
(() => {
  'use strict';
  const root = document.getElementById('footer');
  if (!root) return;
  const { $ } = MM;

  // Updates — client-side only. No backend exists: nothing is sent anywhere.
  const form = $('#footer-news', root), input = $('#footer-email', root);
  const err = $('#footer-email-err', root), done = $('#footer-news-done', root);
  if (!form || !input || !err || !done) return;
  form.noValidate = true;                       // JS owns validation (without JS the form is not rendered: data-js-only)
  const EMAIL = /^[^\s@]+@[^\s@.]+(\.[^\s@.]+)*\.[^\s@.]{2,}$/;
  const valid = () => EMAIL.test(input.value.trim());
  // The error is role="alert": it is announced when it appears, which matters on Enter — focus is already on the
  // field, so re-focusing it fires nothing and the new description alone is not read out.
  const setError = on => {
    input.setAttribute('aria-invalid', on ? 'true' : 'false');
    if (on) input.setAttribute('aria-describedby', err.id); else input.removeAttribute('aria-describedby');
    if (on && !err.hidden) {
      // Already showing: take it out of the accessibility tree for two frames so a repeat invalid submit is
      // announced again. visibility (not [hidden]) keeps its box, so nothing below it jumps.
      err.classList.add('is-reset');
      MM.raf2().then(() => err.classList.remove('is-reset'));
    } else err.hidden = !on;
  };
  input.addEventListener('input', () => { if (input.getAttribute('aria-invalid') === 'true' && valid()) setError(false); });
  form.addEventListener('submit', e => {
    e.preventDefault();
    if (!valid()) { setError(true); input.focus(); return; }
    setError(false);
    form.classList.add('is-sent');
    form.inert = true;
    done.hidden = false;
    done.focus({ preventScroll: true });        // the confirmation is read out; the landing target shows no ring
    MM.raf2().then(() => done.classList.add('is-on'));
  });
})();

/* ── thank-you — thank-you.html ── */
(() => {
  'use strict';
  const root = document.getElementById('thank-you');
  if (!root) return;
  const type = new URLSearchParams(window.location.search).get('type');
  if (type === 'demo') root.setAttribute('data-type', 'demo');
})();
